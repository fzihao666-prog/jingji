export function importFieldGuidance(key: string): ImportFieldGuidance | undefined {
  return guidance[key === '强度%' ? '强度百分比' : key];
}

export function importFieldFillCondition(sheet: string, key: string): string | undefined {
  if (['姓名', '运动员'].includes(key)) return '没有系统编号，或新建人员时填写';
  if (['运动项目', '项目', '所属队伍', '队伍'].includes(key)) return '未由当前项目、队伍预填时填写';
  if (['日期', '测量日期', '测试日期', '发生日期', '评估日期', '训练日期'].includes(key))
    return '上传时未选统一日期，就在本列填日期';
  if (['课次序号', '训练场次'].includes(key)) return '同一人同一天有多次训练时填写';
  if (['组序', '组次'].includes(key)) return '同一动作做了多组时填写';
  if (['时长分钟', '距离千米'].includes(key)) return '时长、距离至少填一项';
  if (key === '测试协议') return '填不对称指数时必须写明测法';
  if (key === '评估协议') return '填一般耐力/核心力量评分时填写';
  if (sheet === '竞技评估' && key === '总分') return '填写专项耐力等竞技评价时提供真实总分';
  if (key === '单位') return '系统不能从指标字典确定单位时填写';
  if (key === '侧别') return '测左侧、右侧或双侧时填写';
  if (sheet === '专项训练成绩') {
    if (key === '运动员姓名') return '组合名称没有列出完整成员时填写';
    if (['艇型', '性别组别'].includes(key)) return '需要按艇型、组别排名时填写';
    if (/^第[123]轮$/.test(key)) return '三轮至少填一轮，未测轮次留空';
  }
  return undefined;
}
